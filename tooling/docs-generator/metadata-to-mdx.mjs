import path from 'node:path';
import { fileURLToPath } from 'node:url';

const generatorDirectory = path.dirname(fileURLToPath(import.meta.url));
export const repoRoot = path.resolve(generatorDirectory, '../..');
export const docsRoot = path.join(repoRoot, 'apps/docs');
export const contentRoot = path.join(docsRoot, 'content');
export const staticRoot = path.join(docsRoot, 'static');
export const generatedContentRoot = path.join(contentRoot, 'generated');
export const generatedStaticRoot = path.join(staticRoot, 'generated');
export const generatedMarker = '<!-- Generated by tooling/docs-generator. Do not edit. -->';
const generationLockPath = path.join(docsRoot, '.docs-generator.lock');

const componentRoot = path.join(repoRoot, 'specs/components');
const patternRoot = path.join(repoRoot, 'specs/patterns');
const figmaMappingPath = path.join(repoRoot, 'figma/mapping/components.json');
const tokenManifestPath = path.join(repoRoot, 'packages/tokens/generated/manifest.json');

const readJson = async (filePath) => JSON.parse(await readFile(filePath, 'utf8'));

const listJsonFiles = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const filePath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await listJsonFiles(filePath)));
    else if (entry.isFile() && entry.name.endsWith('.json')) files.push(filePath);
  }
  return files.sort();
};

const exists = async (filePath) => {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
};

export const slugify = (value) =>
  value
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/\s+/g, '-')
    .replace(/[^a-zA-Z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();

export const displayLabel = (value) =>
  value.replace(/[-_]+/g, ' ').replace(/\b\w/g, (character) => character.toUpperCase());

const posixRelative = (filePath) => path.relative(repoRoot, filePath).split(path.sep).join('/');

const mdText = (value) =>
  String(value ?? '—')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('|', '\\|')
    .replaceAll('\r\n', '<br />')
    .replaceAll('\n', '<br />');

const mdCode = (value) => `\`${String(value ?? '—').replaceAll('`', "'")}\``;

const listValue = (value) => {
  if (Array.isArray(value)) return value.map(mdCode).join(', ');
  if (value && typeof value === 'object') return mdCode(JSON.stringify(value));
  return mdText(value);
};

const storyDetails = async (metadata) => {
  const storyFile = path.join(repoRoot, metadata.source, `${metadata.name}.stories.tsx`);
  if (!(await exists(storyFile))) return { path: null, title: null };
  const source = await readFile(storyFile, 'utf8');
  const title = source.match(/title:\s*['"]([^'"]+)['"]/)?.[1] ?? null;
  return { path: posixRelative(storyFile), title };
};

const componentDetails = async (filePath, figmaComponents) => {
  const metadata = await readJson(filePath);
  const story = await storyDetails(metadata);
  const metadataPath = posixRelative(filePath);
  const specMarkdown = filePath.replace(/\.json$/, '.md');
  const figma = figmaComponents.find(
    (entry) => entry.category === metadata.category && entry.name === metadata.name,
  );
  return {
    ...metadata,
    slug: slugify(metadata.name),
    metadataPath,
    narrativePath: ((await exists(specMarkdown)) && posixRelative(specMarkdown)) || null,
    storyPath: story.path,
    storyTitle: story.title,
    docsPath: `/docs/components/${metadata.category}/${slugify(metadata.name)}`,
    figmaKey: figma?.depoUiKey ?? null,
    figmaComponentSet: figma?.componentSet ?? null,
  };
};

const patternDetails = async (filePath) => {
  const metadata = await readJson(filePath);
  const narrativePath = filePath.replace(/\.json$/, '.md');
  return {
    ...metadata,
    slug: slugify(metadata.id),
    metadataPath: posixRelative(filePath),
    narrativePath: ((await exists(narrativePath)) && posixRelative(narrativePath)) || null,
    docsPath: `/docs/patterns/${slugify(metadata.id)}`,
  };
};

export const collectDocsModel = async () => {
  const figmaMapping = await readJson(figmaMappingPath);
  const tokenManifest = await readJson(tokenManifestPath);
  const componentFiles = await listJsonFiles(componentRoot);
  const patternFiles = await listJsonFiles(patternRoot);
  const components = await Promise.all(
    componentFiles.map((filePath) => componentDetails(filePath, figmaMapping.components ?? [])),
  );
  const patterns = await Promise.all(patternFiles.map(patternDetails));
  const themes = Object.keys(tokenManifest.themes ?? {}).sort();
  const semanticCount = Array.isArray(tokenManifest.semantic)
    ? tokenManifest.semantic.length
    : Object.keys(tokenManifest.semantic ?? {}).length;
  return {
    components: components.sort((left, right) =>
      `${left.category}/${left.name}`.localeCompare(`${right.category}/${right.name}`),
    ),
    patterns: patterns.sort((left, right) => left.id.localeCompare(right.id)),
    tokens: {
      themes,
      referenceCount: Array.isArray(tokenManifest.reference)
        ? tokenManifest.reference.length
        : Object.keys(tokenManifest.reference ?? {}).length,
      semanticCount,
      sourceHash: tokenManifest.sourceHash ?? null,
    },
    figma: {
      mappingPath: 'figma/mapping/components.json',
      componentCount: (figmaMapping.components ?? []).length,
    },
  };
};

const table = (rows) => {
  const lines = ['| Field | Contract |', '| --- | --- |'];
  for (const [key, value] of rows) lines.push(`| ${mdText(key)} | ${listValue(value)} |`);
  return lines.join('\n');
};

