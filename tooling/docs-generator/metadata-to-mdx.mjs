export const docsNavigation = async () => readJson(path.join(docsRoot, 'navigation.json'));

export const generateMdx = async (model) => {
  await rm(generatedContentRoot, { recursive: true, force: true });
  await mkdir(generatedContentRoot, { recursive: true });
  for (const component of model.components) {
    const directory = path.join(generatedContentRoot, 'components', component.category);
    await mkdir(directory, { recursive: true });
    await writeFile(
      path.join(directory, `${component.slug}-api.mdx`),
      componentMdx(component),
      'utf8',
    );
  }
  for (const pattern of model.patterns) {
    const directory = path.join(generatedContentRoot, 'patterns');
    await mkdir(directory, { recursive: true });
    await writeFile(path.join(directory, `${pattern.slug}.mdx`), patternMdx(pattern), 'utf8');
  }
};

const searchEntries = (navigation, model) => [
  ...navigation.map((item) => ({
    title: item.label,
    description: item.description,
    path: item.path,
    kind: 'section',
  })),
  ...model.components.map((component) => ({
    title: component.name,
    description: component.purpose,
    path: component.docsPath,
    kind: 'component',
  })),
  ...model.patterns.map((pattern) => ({
    title: pattern.name,
    description: pattern.purpose,
    path: pattern.docsPath,
    kind: 'pattern',
  })),
];

export const writeManifest = async (navigation, model) => {
  await rm(generatedStaticRoot, { recursive: true, force: true });
  await mkdir(generatedStaticRoot, { recursive: true });
  const manifest = {
    schemaVersion: 1,
    generatedBy: 'tooling/docs-generator',
    marker: generatedMarker,
    navigation,
    counts: {
      components: model.components.length,
      patterns: model.patterns.length,
      searchEntries: searchEntries(navigation, model).length,
    },
    tokens: model.tokens,
    figma: model.figma,
    components: model.components.map((component) => ({
      name: component.name,
      category: component.category,
      lifecycle: component.lifecycle,
      metadataPath: component.metadataPath,
      sourcePath: component.source,
      storyPath: component.storyPath,
      docsPath: component.docsPath,
      figmaKey: component.figmaKey,
    })),
    patterns: model.patterns.map((pattern) => ({
      id: pattern.id,
      name: pattern.name,
      metadataPath: pattern.metadataPath,
      sourcePath: pattern.source ?? null,
      docsPath: pattern.docsPath,
    })),
  };
  await writeFile(
    path.join(generatedStaticRoot, 'docs-manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    path.join(generatedStaticRoot, 'search.json'),
    `${JSON.stringify(searchEntries(navigation, model), null, 2)}\n`,
    'utf8',
  );
  await writeFile(
    path.join(generatedStaticRoot, 'docs-preview.html'),
    previewHtml(navigation, model),
    'utf8',
  );
};

const delay = (milliseconds) =>
  new Promise((resolve) => globalThis.setTimeout(resolve, milliseconds));

const acquireGenerationLock = async () => {
  for (let attempt = 0; attempt < 800; attempt += 1) {
    try {
      return await open(generationLockPath, 'wx');
    } catch (error) {
      if (error.code !== 'EEXIST') throw error;
      try {
        const lockAge = Date.now() - (await stat(generationLockPath)).mtimeMs;
        if (lockAge > 10_000) await unlink(generationLockPath);
      } catch (statError) {
        if (statError.code !== 'ENOENT') throw statError;
      }
      await delay(25);
    }
  }
  throw new Error(`Timed out waiting for docs generation lock: ${generationLockPath}`);
};

export const generateDocs = async () => {
  const lock = await acquireGenerationLock();
  try {
    const model = await collectDocsModel();
    const navigation = await docsNavigation();
    await generateMdx(model);
    await writeManifest(navigation, model);
    return { model, navigation };
  } finally {
    await lock.close();
    await unlink(generationLockPath).catch((error) => {
      if (error.code !== 'ENOENT') throw error;
    });
  }
};
